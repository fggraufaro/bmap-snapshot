def save_deck(prs, bank_name, out_dir=OUT_DIR):
    safe = "".join(c if c.isalnum() or c in " _-" else "_" for c in bank_name).strip()
    date = datetime.now().strftime("%Y%m%d")
    fname = out_dir / f"BMAP_Snapshot_{safe}_{date}.pptx"
    prs.save(str(fname))
    return fname


